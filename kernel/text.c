static const uint8_t mark_below[][2] = {
    /* cedilla */ {0x18, 0x0C},
    /* ogonek  */ {0x0C, 0x18},
};

/* A compressed base keeps the accent clear of ascenders and preserves the
 * shared baseline, so accented and plain Latin letters still line up. */
static void compress_base(const uint8_t *src, uint8_t out[16]) {
    for (int i = 0; i < 16; i++) out[i] = 0;
    for (int row = 4; row < 16; row++) {
        int s = 2 + (row - 4) * 14 / 12;
        if (s > 15) s = 15;
        out[row] = src[s];
    }
}

static const uint8_t *compose_glyph(const struct compose *c) {
    static uint8_t scratch[16];
    const uint8_t *base = font8x16[(unsigned char)c->base & 0x7F];
    if (c->mark == M_CEDILLA || c->mark == M_OGONEK) {
        for (int i = 0; i < 16; i++) scratch[i] = base[i];
        const uint8_t *m = mark_below[c->mark - M_CEDILLA];
        scratch[14] |= m[0];
        scratch[15] |= m[1];
        return scratch;
    }
    compress_base(base, scratch);
    if (c->mark == M_STROKE) {
        for (int i = 0; i < 8; i++) {
            int row = 5 + i;
            if (row < 16) scratch[row] |= (uint8_t)(0x80 >> i);
        }
        return scratch;
    }
    const uint8_t *m = mark_above[c->mark];
    scratch[1] |= m[0];
    scratch[2] |= m[1];
    scratch[3] |= m[2];
    return scratch;
}

