#include <solis/text.h>

/* ASCII glyphs live with the framebuffer code so the boot console keeps
 * working before this module is reachable. */
extern const uint8_t font8x16[128][16];

#define REPLACEMENT 0xFFFDu

int text_decode(const char *s, uint32_t *cp) {
    const unsigned char *p = (const unsigned char *)s;
    uint32_t c = p[0];
    if (c == 0) { if (cp) *cp = 0; return 0; }
    if (c < 0x80) { if (cp) *cp = c; return 1; }

    int need;
    uint32_t value;
    uint32_t min;
    if ((c & 0xE0) == 0xC0) { need = 1; value = c & 0x1F; min = 0x80; }
    else if ((c & 0xF0) == 0xE0) { need = 2; value = c & 0x0F; min = 0x800; }
    else if ((c & 0xF8) == 0xF0) { need = 3; value = c & 0x07; min = 0x10000; }
    else { if (cp) *cp = REPLACEMENT; return 1; }

    for (int i = 1; i <= need; i++) {
        unsigned char cc = p[i];
        if ((cc & 0xC0) != 0x80) { if (cp) *cp = REPLACEMENT; return 1; }
        value = (value << 6) | (cc & 0x3F);
    }
    if (value < min || value > 0x10FFFF ||
        (value >= 0xD800 && value <= 0xDFFF)) {
        if (cp) *cp = REPLACEMENT;
        return 1;
    }
    if (cp) *cp = value;
    return need + 1;
}

int text_encode(uint32_t cp, char *out) {
    if (cp < 0x80) { out[0] = (char)cp; return 1; }
    if (cp < 0x800) {
        out[0] = (char)(0xC0 | (cp >> 6));
        out[1] = (char)(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp >= 0xD800 && cp <= 0xDFFF) return 0;
    if (cp < 0x10000) {
        out[0] = (char)(0xE0 | (cp >> 12));
        out[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        out[2] = (char)(0x80 | (cp & 0x3F));
        return 3;
    }
    if (cp > 0x10FFFF) return 0;
    out[0] = (char)(0xF0 | (cp >> 18));
    out[1] = (char)(0x80 | ((cp >> 12) & 0x3F));
    out[2] = (char)(0x80 | ((cp >> 6) & 0x3F));
    out[3] = (char)(0x80 | (cp & 0x3F));
    return 4;
}

bool text_is_wide(uint32_t cp) {
    return (cp >= 0x1100 && cp <= 0x115F) ||
           (cp >= 0x2E80 && cp <= 0x303E) ||
           (cp >= 0x3041 && cp <= 0x33FF) ||
           (cp >= 0x3400 && cp <= 0x4DBF) ||
           (cp >= 0x4E00 && cp <= 0x9FFF) ||
           (cp >= 0xA000 && cp <= 0xA4CF) ||
           (cp >= 0xAC00 && cp <= 0xD7A3) ||
           (cp >= 0xF900 && cp <= 0xFAFF) ||
           (cp >= 0xFE30 && cp <= 0xFE4F) ||
           (cp >= 0xFF00 && cp <= 0xFF60) ||
           (cp >= 0xFFE0 && cp <= 0xFFE6) ||
           (cp >= 0x1F300 && cp <= 0x1FAFF) ||
           (cp >= 0x20000 && cp <= 0x3FFFD);
}

int text_advance(uint32_t cp) {
    if (cp == '\t') return 0; /* handled by the measuring loop */
    if (cp == 0x200B || cp == 0x200C || cp == 0x200D || cp == 0xFEFF)
        return 0; /* zero-width formatting characters */
    if (cp >= 0x0300 && cp <= 0x036F) return 0; /* combining marks */
    if (text_is_wide(cp)) return 16;
    return 8;
}

