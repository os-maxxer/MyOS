const uint8_t *text_glyph(uint32_t cp, int *width) {
    if (width) *width = 8;
    if (cp < 0x80) return font8x16[cp & 0x7F];

    for (unsigned i = 0; i < sizeof(compose_table) / sizeof(compose_table[0]); i++) {
        if (compose_table[i].cp == cp)
            return compose_glyph(&compose_table[i]);
    }
    for (unsigned i = 0; i < sizeof(extra_glyphs) / sizeof(extra_glyphs[0]); i++) {
        if (extra_glyphs[i].cp == cp) return extra_glyphs[i].rows;
    }
    for (unsigned i = 0; i < sizeof(fold_table) / sizeof(fold_table[0]); i++) {
        if (fold_table[i].cp == cp) return font8x16[fold_table[i].ascii & 0x7F];
    }
    if (cp == 0xFFFD) return tofu;
    if (text_is_wide(cp)) {
        if (width) *width = 16;
        return tofu_wide;
    }
    return tofu;
}

