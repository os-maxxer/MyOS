int text_width_bytes(const char *s, int len) {
    int x = 0;
    int i = 0;
    while (i < len && s[i]) {
        uint32_t cp;
        int used = text_decode(s + i, &cp);
        if (used <= 0) break;
        if (used > len - i) used = len - i;
        if (cp == '\n' || cp == '\r') { x = 0; i += used; continue; }
        if (cp == '\t') { x += 8 * (4 - ((x / 8) & 3)); i += used; continue; }
        x += text_advance(cp);
        i += used;
    }
    return x;
}

int text_width(const char *s) {
    int len = 0;
    while (s[len]) len++;
    return text_width_bytes(s, len);
}

int text_clip(const char *src, char *dst, int dst_max, int max_px) {
    int x = 0, si = 0, di = 0;
    while (src[si] && di < dst_max - 1) {
        uint32_t cp;
        int used = text_decode(src + si, &cp);
        if (used <= 0) break;
        int adv = (cp == '\t') ? 8 : text_advance(cp);
        if (x + adv > max_px) break;
        for (int i = 0; i < used && di < dst_max - 1; i++)
            dst[di++] = src[si + i];
        x += adv;
        si += used;
    }
    dst[di] = '\0';
    return di;
}
